def floor_object_points() -> tuple[np.ndarray, dict[int, np.ndarray]]:
    """바닥 마커들의 map 좌표계 코너 4점 묶음 (z = 0).

    바닥 마커는 눕혀 붙이므로 네 코너 모두 z = 0 이다.
    마커 하나당 4점이므로 4장이면 16점 — 외부파라미터가 훨씬 안정된다.
    코너 순서는 ArUco 검출 순서와 같다: 좌상, 우상, 우하, 좌하
    (인쇄물 윗변이 +y 를 향하게 붙였다는 전제)
    """
    per_id = {}
    h = FLOOR_MARKER_SIZE / 2.0
    for mid, (cx, cy) in FLOOR_MARKER_WORLD.items():
        per_id[mid] = np.array([
            [cx - h, cy + h, 0.0],
            [cx + h, cy + h, 0.0],
            [cx + h, cy - h, 0.0],
            [cx - h, cy - h, 0.0],
        ], dtype=np.float64)
    allpts = np.vstack([per_id[m] for m in sorted(per_id)])
    return allpts, per_id


def approx_camera_matrix(w: int = IMG_W, h: int = IMG_H,
                         hfov_deg: float = HFOV_DEG) -> np.ndarray:
    """캘리브레이션 파일이 없을 때 쓰는 근사 내부파라미터.

    ⚠️ 배선 확인용 임시값이다. 정확도를 맞추려면 calibrate_camera.py 를 돌릴 것.
    """
    fx = (w / 2.0) / math.tan(math.radians(hfov_deg) / 2.0)
    return np.array([[fx, 0.0, w / 2.0],
                     [0.0, fx, h / 2.0],
                     [0.0, 0.0, 1.0]], dtype=np.float64)
