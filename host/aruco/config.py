#
# localizer 는 yaw 를 코너0→코너1 방향, 곧 "종이의 오른쪽" 방향으로 잰다.
# 로봇에는 "종이 위쪽 = 로봇 앞쪽"으로 붙이는 게 직관적이라 그 차이 90도를
# 기본값으로 둔다.
#     종이 위쪽 = 로봇 앞쪽   →  90.0  (기본값, 권장)
#     종이 오른쪽 = 로봇 앞쪽 →   0.0
# 다르게 붙였으면 사용법.txt 9단계의 보정 절차로 이 값을 구하면 된다.
# 2026-09-06 실측으로 90.0 -> 85.7. 로봇을 두 축에 각각 맞춰 놓고 정지 상태의
# yaw 를 읽었다(host/calib_yaw_static.py).
#
#     +x 를 향함   읽힘 +5.06도  (기대 0)     치우침 +5.06
#     +y 를 향함   읽힘 +93.52도 (기대 +90)   치우침 +3.52
#
# 서로 독립적으로 놓은 두 자세에서 같은 방향으로 치우쳤다 — 놓기 오차가
# 아니라 실제 축 어긋남이다. 두 값의 차 1.5도가 놓기 오차의 크기다.
#
# 이 값이 틀리면 로봇은 정면을 봤다고 판단하고 직진하는데 실제로는 비스듬히
# 간다. 4.3도는 DRIVE_YAW_TOLERANCE_DEG(5도)와 비슷한 크기라 허용치를 상시로
# 갉아먹는다.
#
# ⚠️ 더 정확한 방법은 host/calib_yaw_axis.py 다 — 로봇을 직진시켜 바퀴가 만든
# 실제 이동 방향과 비교하므로 사람 판단이 안 들어간다. 2026-09-06 에는 배터리가
# 6.9V 라 차가 못 움직여서 정지 방식으로 잡았다. 충전 뒤 다시 재서 확정할 것.
# 2026-09-06 주행 실측으로 91.4. 로봇을 직진시켜 **바퀴가 만든 실제 이동
# 방향**과 보고된 yaw 를 비교했다(host/calib_yaw_axis.py). 사람이 로봇을 축에
# 맞춰 놓는 정확도에 안 기대는 방법이다.
#
#     재부팅 전   차이 +5.7도  회차 편차 2.3도  (4회 전부 유효)
#     재부팅 후   차이 +5.7도  회차 편차 2.2도  (유효 3회)
#     91.4 에서   차이 -2.2도  회차 편차 0.4도  (유효 2회) -> 89.2
#
# 남은 오차 2도는 DRIVE_YAW_TOLERANCE_DEG(12도)의 6분의 1이라 주행에
